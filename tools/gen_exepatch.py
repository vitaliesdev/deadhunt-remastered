"""Generates ExePatchData.inl: the byte changes the remaster makes to Deadhunt.exe (code caves and hooks
written by the old patch_*.py scripts), as in-memory patches that DeadhuntFX applies at start-up, so
the game's exe on disk is never modified. Runs inside the PE headers (section flags that made .text
writable) are left out: in memory VirtualProtect does that job.
    python gen_exepatch.py <original Deadhunt.exe> <patched Deadhunt.exe> <out .inl>
"""
import sys
import pefile

orig_path, mod_path, out = sys.argv[1:4]
orig, mod = open(orig_path, "rb").read(), open(mod_path, "rb").read()
assert len(orig) == len(mod)
pe = pefile.PE(orig_path)
base = pe.OPTIONAL_HEADER.ImageBase
hdr = pe.OPTIONAL_HEADER.SizeOfHeaders


def va_of(off):
    for s in pe.sections:
        if s.PointerToRawData <= off < s.PointerToRawData + s.SizeOfRawData:
            return base + s.VirtualAddress + off - s.PointerToRawData
    return None


runs, i = [], 0
while i < len(orig):
    if orig[i] != mod[i]:
        j = i
        while j < len(orig) and orig[j] != mod[j]:
            j += 1
        runs.append((i, orig[i:j], mod[i:j]))
        i = j
    else:
        i += 1

lines = ["// Generated by tools/gen_exepatch.py - in-memory patches of Deadhunt.exe. Do not edit.",
         "struct ExeRun { DWORD va; WORD len; const unsigned char* orig; const unsigned char* mod; };"]
items = []
for n, (off, a, b) in enumerate(runs):
    if off < hdr:
        continue
    va = va_of(off)
    assert va, hex(off)
    fa = ", ".join("0x%02x" % x for x in a)
    fb = ", ".join("0x%02x" % x for x in b)
    lines.append("static const unsigned char kRunO%d[] = { %s };" % (n, fa))
    lines.append("static const unsigned char kRunM%d[] = { %s };" % (n, fb))
    items.append("    { 0x%x, %d, kRunO%d, kRunM%d }," % (va, len(a), n, n))
lines.append("static const ExeRun kExeRuns[] = {")
lines += items
lines.append("};")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print(len(items), "parches en memoria (", len(runs) - len(items), "en cabeceras omitidos )")
