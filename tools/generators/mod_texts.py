r"""Generates src/frontend/l10n/l10n_strings.inl from localization/mod/strings.py.

The game draws text as single bytes, so each string is written as escaped bytes in its language's
encoding: cp1252 for the Western languages (our font set Data\FontE), cp1250 for Polish (Data\FontP),
cp1251 for Russian and Ukrainian (the original fonts) and ASCII for English.
    python tools\generators\mod_texts.py [out .inl]
"""
import os, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "localization", "mod"))
from strings import CODES, ENC, S, LANG_NAMES

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "src", "frontend", "l10n", "l10n_strings.inl")
N = len(CODES)


def esc(text, enc):
    out = ""
    for b in text.encode(enc):
        out += chr(b) if 32 <= b < 127 and chr(b) not in '"\\' else '\\x%02X""' % b
    return '"' + out + '"'


assert all(len(s) == N + 1 for s in S) and all(len(n) == N for n in LANG_NAMES)
lines = ["// Generated by tools/generators/mod_texts.py - DeadhuntFX texts in every language of the mod. Do not edit.",
         "// cp1252 (es fr de it pt), ASCII (en), cp1251 (ru uk), cp1250 (pl): the game's text is single-byte.",
         "",
         "enum { %s, LANG_COUNT };" % ", ".join("LANG_%s = %d" % (c.upper(), i) for i, c in enumerate(CODES)),
         "static const wchar_t* const kLangCode[LANG_COUNT] = { %s };" % ", ".join('L"%s"' % c for c in CODES),
         "enum Str {"]
lines += ["    " + s[0] + "," for s in S]
lines += ["    STR_COUNT", "};", "", "static const char* const kStr[STR_COUNT][LANG_COUNT] = {"]
for s in S:
    lines.append("    { %s }," % ", ".join(esc(s[1 + i], ENC[i]) for i in range(N)))
lines += ["};", ""]
lines.append("static const char* const kLangName[LANG_COUNT][LANG_COUNT] = {   // [current language][language]")
for cur in range(N):
    lines.append("    { %s }," % ", ".join(esc(n, ENC[cur]) for n in LANG_NAMES[cur]))
lines += ["};", "", "static int g_lang = LANG_ES;", "static const char* Tr(int id) { return kStr[id][g_lang]; }", ""]
open(OUT, "w", encoding="ascii", newline="\r\n").write("\n".join(lines))   # Windows line ends, like a git checkout
print(len(S), "textos,", N, "idiomas")
